#include "GameModel.h"
#include "GameManager.h"

// ============================================================
// コンストラクタ：ゲームの初期状態を設定
// ============================================================
GameModel::GameModel()
    : currentEnemy(nullptr), currentMap(0), defeatedOnMap(0)
{
    // メンバ変数の初期化
    // currentEnemy: 現在のバトル敵（最初はなし）
    // currentMap: 現在のマップ番号（0番目から開始）
    // defeatedOnMap: 現在のマップで倒した敵の数（0から開始）
}

// ============================================================
// プレイヤー情報の取得（非const版）
// ============================================================
Player& GameModel::GetPlayer()
{
    // プレイヤーオブジェクトへの参照を返す
    // Controllerやその他の処理でプレイヤー情報を変更する際に使用
    return player;
}

// ============================================================
// プレイヤー情報の取得（const版）
// ============================================================
const Player& GameModel::GetPlayer() const
{
    // 読み取り専用のプレイヤーオブジェクト参照を返す
    // Viewでプレイヤー情報を表示する際に使用（変更不可）
    return player;
}

// ============================================================
// 現在のバトル敵を取得
// ============================================================
Enemy* GameModel::GetCurrentEnemy() const
{
    // 現在戦闘中の敵オブジェクトへのポインタを返す
    // nullptrの場合は敵がいない状態
    return currentEnemy;
}

// ============================================================
// 現在のマップ番号を取得
// ============================================================
int GameModel::GetCurrentMap() const
{
    // プレイヤーが現在いるマップの番号を返す（0ベース）
    // マップデータの取得やマップ判定に使用
    return currentMap;
}

// ============================================================
// 現在のマップで倒した敵の数を取得
// ============================================================
int GameModel::GetDefeatedOnMap() const
{
    // マップクリアの判定に使用される敵討伐数を返す
    // マップの敵の総数と比較してクリア判定
    return defeatedOnMap;
}

// ============================================================
// 敵のオブジェクトプールを取得
// ============================================================
ObjectPool& GameModel::GetEnemyPool()
{
    // 敵のメモリプール管理オブジェクトへの参照を返す
    // 敵の生成や解放に使用
    return enemyPool;
}

// ============================================================
// 現在のバトル敵を設定
// ============================================================
void GameModel::SetCurrentEnemy(Enemy* enemy)
{
    // 新しい敵をバトルの対象として設定
    // 敵の生成時やバトル終了時に呼び出される
    currentEnemy = enemy;
}

// ============================================================
// 現在のマップ番号を設定
// ============================================================
void GameModel::SetCurrentMap(int map)
{
    // プレイヤーが進むマップを設定
    // マップクリア後に次のマップへ進む際に呼び出される
    currentMap = map;
}

// ============================================================
// マップ上での敵討伐数を設定
// ============================================================
void GameModel::SetDefeatedOnMap(int count)
{
    // 現在のマップで倒した敵の数を直接設定
    // ゲーム初期化やマップ遷移時にリセットするために使用
    defeatedOnMap = count;
}

// ============================================================
// マップ上での敵討伐数をインクリメント
// ============================================================
void GameModel::IncrementDefeatedOnMap()
{
    // 敵を倒した時に討伐数を1増加させる
    // マップクリア条件の判定に用いられる
    defeatedOnMap++;
}

// ============================================================
// ゲーム全体の状態をリセット（ゲーム開始時に呼び出し）
// ============================================================
void GameModel::ResetGameState()
{
    // タイトル画面から新規ゲーム開始する際に
    // すべてのゲーム状態を初期状態に戻す

    // 新しいプレイヤーオブジェクトを生成（HP回復、レベルリセット等）
    player = Player();

    // 敵のオブジェクトプールをリセット（全敵をプールに戻す）
    enemyPool.Reset();

    // 現在のバトル敵をなしにする
    currentEnemy = nullptr;

    // マップを最初の番号（0）にリセット
    currentMap = 0;

    // マップ上の敵討伐数をリセット
    defeatedOnMap = 0;
}

// ============================================================
// プレイヤーの攻撃を実行し、ダメージを計算
// ============================================================
void GameModel::ExecutePlayerAttack(int& outDamage)
{
    // プレイヤーの攻撃フラグやカウンターを更新
    player.Attack();

    // プレイヤーの攻撃力を取得
    outDamage = player.GetAttack();

    // 敵が存在する場合、敵にダメージを与える
    if (currentEnemy != nullptr)
    {
        currentEnemy->TakeDamage(outDamage);
    }
    // 戻り値の outDamage にダメージ値が格納され、
    // Controllerで表示（View）に渡される
}

// ============================================================
// 敵の攻撃を実行し、プレイヤーがダメージを受ける
// ============================================================
void GameModel::ExecuteEnemyAttack(int& outDamage)
{
    // 敵が存在する場合のみ処理を実行
    if (currentEnemy != nullptr)
    {
        // 敵の攻撃力を取得
        outDamage = currentEnemy->GetAttack();

        // プレイヤーが敵からダメージを受ける
        player.TakeDamage(outDamage);
    }
    // 戻り値の outDamage にダメージ値が格納され、
    // Controllerで表示（View）に渡される
}

// ============================================================
// プレイヤーが回復薬を使用して HP を回復
// ============================================================
void GameModel::ExecutePlayerHeal(int healAmount)
{
    // プレイヤーの HP を指定量だけ回復する
    // healAmount: 回復量（例: 20 HP）
    player.Heal(healAmount);
}

// ============================================================
// 敵を倒した時の報酬処理（EXP とゴールド獲得）
// ============================================================
void GameModel::HandleEnemyDefeated(int& outExp, int& outGold)
{
    // 敵が存在しない場合は処理をスキップ
    if (currentEnemy == nullptr)
    {
        outExp = 0;
        outGold = 0;
        return;
    }

    // 現在のマップデータを取得（マップごとの報酬倍率が含まれている）
    const MapData& map = GetMapData(currentMap);

    // 敵の基本 EXP にマップの倍率を乗算して獲得 EXP を計算
    outExp = currentEnemy->GetExp() * map.expMultiplier;

    // 敵の基本ゴールドにマップの倍率を乗算して獲得ゴールドを計算
    outGold = currentEnemy->GetGold() * map.goldMultiplier;

    // プレイヤーの EXP を追加（レベルアップ判定も内部で実行される）
    player.AddExp(outExp);

    // プレイヤーのゴールドを追加
    player.AddGold(outGold);

    // GameManager に敵討伐数をカウント（統計情報管理）
    GameManager::GetInstance().AddDefeatedEnemy();

    // 敵をオブジェクトプールに返却（メモリ再利用のため）
    enemyPool.ReleaseEnemy(currentEnemy);

    // 現在のバトル敵をなしにする
    currentEnemy = nullptr;
}