#include "Enemy.h"

// ============================================================
// コンストラクタ：敵の初期状態を設定
// ============================================================
Enemy::Enemy()
    : hp(0), maxHp(0), attack(0), exp(0), gold(0), active(false)
{
    // name は std::string のデフォルトコンストラクタで初期化される
}

// ============================================================
// 敵を敵データで初期化
// ============================================================
void Enemy::Initialize(const EnemyData& data)
{
    // 敵データから状態をコピー
    name = data.name;      // std::string でコピー（安全）
    maxHp = data.maxHp;
    hp = maxHp;
    attack = data.attack;
    exp = data.exp;
    gold = data.gold;
    active = true;
}

// ============================================================
// ダメージを受ける（HP減少）
// ============================================================
void Enemy::TakeDamage(int damage)
{
    // 受けたダメージ分 HP を減少
    hp -= damage;

    // HP が負にならないようにクランプ
    if (hp < 0)
    {
        hp = 0;
    }
}

// ============================================================
// 敵の状態をリセット（オブジェクトプール復帰時に呼び出し）
// ============================================================
void Enemy::Reset()
{
    name = "";      // std::string でクリア
    hp = 0;
    maxHp = 0;
    attack = 0;
    gold = 0;
    exp = 0;
    active = false;
}

// ============================================================
// 敵がアクティブ（使用中）か確認
// ============================================================
bool Enemy::IsActive() const
{
    return active;
}

// ============================================================
// 敵が倒れたか確認（HP <= 0）
// ============================================================
bool Enemy::IsDead() const
{
    return hp <= 0;
}

// ============================================================
// 敵の名前を取得
// ============================================================
const char* Enemy::GetName() const
{
    // std::string から const char* に変換（安全）
    // empty() の場合も "" を返す
    return name.c_str();
}

// ============================================================
// 現在の HP を取得
// ============================================================
int Enemy::GetHP() const
{
    return hp;
}

// ============================================================
// 最大 HP を取得
// ============================================================
int Enemy::GetMaxHP() const
{
    return maxHp;
}

// ============================================================
// 攻撃力を取得
// ============================================================
int Enemy::GetAttack() const
{
    return attack;
}

// ============================================================
// 獲得 EXP を取得
// ============================================================
int Enemy::GetExp() const
{
    return exp;
}

// ============================================================
// 獲得ゴールドを取得
// ============================================================
int Enemy::GetGold() const
{
    return gold;
}