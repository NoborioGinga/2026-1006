#include "Player.h"
#include <iostream>

// ============================================================
// コンストラクタ：プレイヤーの初期状態を設定
// ============================================================
Player::Player()
    : hp(100), maxHp(100), attack(20), exp(0), gold(0), 
      level(1), nextLevelExp(100), leveledUp(false)
{
}

// ============================================================
// 攻撃処理（攻撃フラグ等の更新）
// ============================================================
void Player::Attack()
{
    // 攻撃フラグやカウンターの更新は必要に応じて実装
    // 現在は攻撃力の取得のみで十分
}

// ============================================================
// ダメージ受ける（HP減少）
// ============================================================
void Player::TakeDamage(int damage)
{
    // 受けたダメージ分 HP を減少
    hp -= damage;

    // HP が負にならないようにクランプ
    if (hp < 0)
    {
        hp = 0;
    }
}

// ============================================================
// HP 回復（回復薬使用時）
// ============================================================
void Player::Heal(int amount)
{
    // 回復量分 HP を増加
    hp += amount;

    // HP が最大値を超えないようにクランプ
    if (hp > maxHp)
    {
        hp = maxHp;
    }
}

// ============================================================
// EXP を獲得（敵撃破時に呼び出し）
// ============================================================
void Player::AddExp(int amount)
{
    // 0 以下の EXP は無視
    if (amount <= 0)
    {
        return;
    }

    // EXP を加算
    exp += amount;

    // レベルアップ判定ループ
    // 複数レベルアップの可能性に対応
    while (exp >= nextLevelExp)
    {
        LevelUp();
    }
}

// ============================================================
// ゴールドを獲得（敵撃破時に呼び出し）
// ============================================================
void Player::AddGold(int amount)
{
    gold += amount;
}

// ============================================================
// プレイヤーが倒れたか確認
// ============================================================
bool Player::IsDead() const
{
    return hp <= 0;
}

// ============================================================
// レベルアップしたか確認
// ============================================================
bool Player::IsLeveledUp() const
{
    return leveledUp;
}

// ============================================================
// 現在の HP を取得
// ============================================================
int Player::GetHP() const
{
    return hp;
}

// ============================================================
// 最大 HP を取得
// ============================================================
int Player::GetMaxHP() const
{
    return maxHp;
}

// ============================================================
// 攻撃力を取得
// ============================================================
int Player::GetAttack() const
{
    return attack;
}

// ============================================================
// 現在の EXP を取得
// ============================================================
int Player::GetExp() const
{
    return exp;
}

// ============================================================
// 現在のゴールドを取得
// ============================================================
int Player::GetGold() const
{
    return gold;
}

// ============================================================
// 現在のレベルを取得
// ============================================================
int Player::GetLevel() const
{
    return level;
}

// ============================================================
// 次のレベルアップに必要な累積 EXP を取得
// ============================================================
int Player::GetNextLevelExp() const
{
    return nextLevelExp;
}

// ============================================================
// レベルアップフラグをリセット
// ============================================================
void Player::ResetLevelUpFlag()
{
    leveledUp = false;
}

// ============================================================
// レベルアップ処理（内部用・プライベート）
// ============================================================
void Player::LevelUp()
{
    // レベルを1上昇
    level++;

    // 最大 HP を 7 上昇
    maxHp += 7;

    // 攻撃力を 2 上昇
    attack += 2;

    // HP を全回復
    hp = maxHp;

    // 次のレベルに必要な累積 EXP を計算
    // 基本値 100 + (レベル - 2) * 50
    nextLevelExp += 100 + (level - 2) * 50;

    // レベルアップフラグを立てる
    // View で表示するために使用される
    leveledUp = true;
}